#!/usr/bin/env node
// Embeds originMigration.js in the Swift module as OriginMigrationScript.swift,
// so the script ships inside the native code with no resource bundle to
// package. Run after editing the script:
//
//   node vendor/UnderwayEngine/packages/shell/modules/static-server/web/embed.js
//
// staticServerPort.test.ts refuses a Swift copy that is not this script.
const fs = require('fs');
const path = require('path');

const source = path.join(__dirname, 'originMigration.js');
const target = path.join(__dirname, '..', 'ios', 'OriginMigrationScript.swift');
const script = fs.readFileSync(source, 'utf8');
if (script.includes('"""#')) throw new Error('the script cannot contain the raw-string delimiter """#');

const swift = [
  '// GENERATED by web/embed.js from web/originMigration.js — edit that file and',
  '// run the script again; never edit this one. The copy an install\'s saved',
  '// work takes from the port it used to live on to the one it lives on now',
  '// (StaticServerModule.swift `adoptLegacyOrigin`), inlined into both of its',
  '// pages. A raw string: nothing in it is interpolated or escaped.',
  '',
  'let originMigrationScript = #"""',
  script.endsWith('\n') ? script.slice(0, -1) : script,
  '"""#',
  '',
].join('\n');
fs.writeFileSync(target, swift);
console.log(`wrote ${path.relative(process.cwd(), target)} (${script.length} chars)`);
