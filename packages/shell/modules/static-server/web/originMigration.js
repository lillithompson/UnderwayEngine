/*
 * One origin's saved work, copied to another.
 *
 * The page's origin is http://localhost:<port>, and the origin is the key to
 * everything the web side stores — IndexedDB, localStorage. An app that moves
 * to its own port (StaticServerModule.swift `port`) therefore leaves every
 * install's journal behind on the old one, and this is how it brings it
 * along: every IndexedDB database (its schema — stores, key paths, key
 * generators, indexes — and every record) and every localStorage entry,
 * read on the old origin and written on the new, then counted on both sides
 * and refused unless the counts agree.
 *
 * It runs inside WebKit, in two pages at once: the PARENT is a hidden
 * WKWebView whose document was given the OLD origin (loadHTMLString's
 * baseURL, so no server need listen on that port), and the CHILD is an
 * iframe in it, served by this app's server on the NEW origin
 * (`/__underway/origin-migration`). Records cross between them with
 * postMessage — structured clone carries ArrayBuffers and Blobs as they
 * are — a page at a time, each page acknowledged before the next is read,
 * so memory stays bounded whatever the journal's size (the WebView's
 * failure mode is memory). The parent reports progress, the result or the
 * error to the native side (`report`), which marks the install migrated
 * only on `done`.
 *
 * Plain script, no imports: it is embedded in the Swift module
 * (OriginMigrationScript.swift, generated by embed.js — run that after
 * editing this file) and inlined into both pages. Under jest it is a
 * CommonJS module, driven with fake-indexeddb and stand-in windows
 * (packages/shell/src/server/__tests__/originMigration.test.ts).
 */
(function (root, factory) {
  var api = factory();
  if (typeof module === 'object' && module && module.exports) module.exports = api;
  else root.UnderwayOriginMigration = api;
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  // A page of records: this many at most, and the count adapts to their
  // size so a page stays near PAGE_BYTES — a journal's thumbnails are
  // megabytes each, its settings a few bytes.
  var PAGE_RECORDS_MAX = 256;
  var PAGE_RECORDS_MIN = 1;
  var PAGE_BYTES = 4 * 1024 * 1024;

  function request(req) {
    return new Promise(function (resolve, reject) {
      req.onsuccess = function () { resolve(req.result); };
      req.onerror = function () { reject(req.error || new Error('IndexedDB request failed')); };
    });
  }

  function transactionDone(tx) {
    return new Promise(function (resolve, reject) {
      tx.oncomplete = function () { resolve(); };
      tx.onerror = function () { reject(tx.error || new Error('IndexedDB transaction failed')); };
      tx.onabort = function () { reject(tx.error || new Error('IndexedDB transaction aborted')); };
    });
  }

  function openDatabase(idb, name, version, upgrade) {
    return new Promise(function (resolve, reject) {
      var req = version === undefined ? idb.open(name) : idb.open(name, version);
      if (upgrade) {
        req.onupgradeneeded = function () {
          try { upgrade(req.result); } catch (e) { reject(e); }
        };
      }
      req.onblocked = function () { reject(new Error('open blocked: ' + name)); };
      req.onsuccess = function () { resolve(req.result); };
      req.onerror = function () { reject(req.error || new Error('open failed: ' + name)); };
    });
  }

  function deleteDatabase(idb, name) {
    return new Promise(function (resolve, reject) {
      var req = idb.deleteDatabase(name);
      req.onblocked = function () { reject(new Error('delete blocked: ' + name)); };
      req.onsuccess = function () { resolve(); };
      req.onerror = function () { reject(req.error || new Error('delete failed: ' + name)); };
    });
  }

  function listOf(domStringList) {
    var out = [];
    for (var i = 0; i < domStringList.length; i++) out.push(domStringList[i]);
    return out;
  }

  // A key path is null, a string or an array of strings; as read from an
  // open store it may be a DOMStringList, which structured clone cannot
  // carry — so it becomes a plain array here.
  function plainKeyPath(keyPath) {
    if (keyPath === null || keyPath === undefined) return null;
    if (typeof keyPath === 'string') return keyPath;
    return listOf(keyPath);
  }

  /** What an open database is made of, as the importer must recreate it. */
  function readSchema(db) {
    var names = listOf(db.objectStoreNames);
    var stores = [];
    if (names.length) {
      var tx = db.transaction(names, 'readonly');
      names.forEach(function (storeName) {
        var store = tx.objectStore(storeName);
        var indexes = listOf(store.indexNames).map(function (indexName) {
          var index = store.index(indexName);
          return {
            name: index.name,
            keyPath: plainKeyPath(index.keyPath),
            unique: !!index.unique,
            multiEntry: !!index.multiEntry,
          };
        });
        stores.push({
          name: store.name,
          keyPath: plainKeyPath(store.keyPath),
          autoIncrement: !!store.autoIncrement,
          indexes: indexes,
        });
      });
    }
    return { name: db.name, version: db.version, stores: stores };
  }

  // Roughly how much memory a value takes, to size the next page.
  function sizeOf(value, depth) {
    if (value === null || value === undefined) return 8;
    var t = typeof value;
    if (t === 'string') return value.length * 2;
    if (t !== 'object') return 8;
    if (typeof ArrayBuffer !== 'undefined') {
      if (value instanceof ArrayBuffer) return value.byteLength;
      if (ArrayBuffer.isView(value)) return value.byteLength;
    }
    if (typeof Blob !== 'undefined' && value instanceof Blob) return value.size;
    if (depth > 6) return 64;
    var total = 16;
    if (Array.isArray(value)) {
      for (var i = 0; i < value.length; i++) total += sizeOf(value[i], depth + 1);
      return total;
    }
    for (var k in value) {
      if (Object.prototype.hasOwnProperty.call(value, k)) total += k.length * 2 + sizeOf(value[k], depth + 1);
    }
    return total;
  }

  function nextPageSize(current, bytes) {
    if (bytes > PAGE_BYTES) return Math.max(PAGE_RECORDS_MIN, Math.floor(current / 2));
    if (bytes < PAGE_BYTES / 4) return Math.min(PAGE_RECORDS_MAX, current * 2);
    return current;
  }

  /**
   * Reads one store in key order, a page per transaction (a transaction
   * does not survive the await on `send`), and sends each page as
   * `{ type: 'records', database, store, keys, values }`. Resolves to the
   * record count.
   */
  async function exportStore(db, storeName, send, firstPageSize) {
    var pageSize = firstPageSize || 32;
    var lastKey;
    var count = 0;
    for (;;) {
      var tx = db.transaction(storeName, 'readonly');
      var store = tx.objectStore(storeName);
      var range = lastKey === undefined ? null : IDBKeyRange.lowerBound(lastKey, true);
      // Both requests are queued before either is awaited: the transaction
      // is still active when the second is made whatever the engine's
      // microtask timing.
      var keysReq = store.getAllKeys(range, pageSize);
      var valuesReq = store.getAll(range, pageSize);
      var keys = await request(keysReq);
      var values = await request(valuesReq);
      if (keys.length === 0) break;
      if (values.length !== keys.length) {
        throw new Error('page mismatch in ' + db.name + '/' + storeName + ': ' + keys.length + ' keys, ' + values.length + ' values');
      }
      lastKey = keys[keys.length - 1];
      count += keys.length;
      var bytes = 0;
      for (var i = 0; i < values.length; i++) bytes += sizeOf(values[i], 0);
      await send({ type: 'records', database: db.name, store: storeName, keys: keys, values: values });
      pageSize = nextPageSize(pageSize, bytes);
    }
    return count;
  }

  function storageEntries(storage) {
    var entries = [];
    if (!storage) return entries;
    for (var i = 0; i < storage.length; i++) {
      var key = storage.key(i);
      if (key !== null) entries.push([key, storage.getItem(key)]);
    }
    return entries;
  }

  /**
   * Copies every database `idb` lists and every entry of `storage` through
   * `send(message) → Promise<reply>`; the importer at the other end is
   * {@link createImporter}. The `finish` message's reply carries the
   * importer's counts, which must equal what was sent — a shortfall is an
   * error, never a partial success. Resolves to the totals.
   *
   * `options.pageSize` is the first page's record count (tests use a small
   * one to exercise paging).
   */
  async function exportOrigin(idb, storage, send, options) {
    if (!idb || typeof idb.databases !== 'function') {
      throw new Error('indexedDB.databases() is unavailable');
    }
    var infos = await idb.databases();
    var names = infos
      .map(function (info) { return info.name; })
      .filter(function (name) { return typeof name === 'string'; })
      .sort();
    var sent = {};
    var records = 0;
    for (var n = 0; n < names.length; n++) {
      var db = await openDatabase(idb, names[n]);
      try {
        var schema = readSchema(db);
        await send({ type: 'database', schema: schema });
        sent[schema.name] = {};
        for (var s = 0; s < schema.stores.length; s++) {
          var storeName = schema.stores[s].name;
          var count = await exportStore(db, storeName, send, options && options.pageSize);
          sent[schema.name][storeName] = count;
          records += count;
        }
      } finally {
        db.close();
      }
    }
    var entries = storageEntries(storage);
    await send({ type: 'localStorage', entries: entries });
    var reply = await send({ type: 'finish' });
    verifyCounts(sent, entries.length, reply);
    return { databases: names.length, records: records, localStorage: entries.length };
  }

  function verifyCounts(sent, localStorageCount, reply) {
    if (!reply || typeof reply !== 'object' || !reply.counts) {
      throw new Error('the importer sent no counts');
    }
    for (var dbName in sent) {
      if (!Object.prototype.hasOwnProperty.call(sent, dbName)) continue;
      var got = reply.counts[dbName];
      if (!got) throw new Error('database missing after import: ' + dbName);
      for (var storeName in sent[dbName]) {
        if (!Object.prototype.hasOwnProperty.call(sent[dbName], storeName)) continue;
        if (got[storeName] !== sent[dbName][storeName]) {
          throw new Error('count mismatch in ' + dbName + '/' + storeName + ': sent ' + sent[dbName][storeName] + ', imported ' + (got[storeName] === undefined ? 'none' : got[storeName]));
        }
      }
    }
    if (reply.localStorage !== localStorageCount) {
      throw new Error('localStorage mismatch: sent ' + localStorageCount + ', imported ' + reply.localStorage);
    }
  }

  /**
   * The receiving end of {@link exportOrigin}: `handle(message)` applies one
   * message to `idb` / `storage` and resolves to its reply. A `database`
   * message drops any database of that name first, so a run that was
   * interrupted (the app killed mid-copy) starts that database over, and
   * `localStorage` replaces the whole store likewise. Messages are handled
   * one at a time, in order.
   */
  function createImporter(idb, storage) {
    var open = {};
    async function handle(message) {
      switch (message && message.type) {
        case 'database': {
          var schema = message.schema;
          if (open[schema.name]) {
            open[schema.name].close();
            delete open[schema.name];
          }
          await deleteDatabase(idb, schema.name);
          var db = await openDatabase(idb, schema.name, schema.version, function (upgrading) {
            schema.stores.forEach(function (s) {
              var store = upgrading.createObjectStore(s.name, { keyPath: s.keyPath, autoIncrement: s.autoIncrement });
              s.indexes.forEach(function (ix) {
                store.createIndex(ix.name, ix.keyPath, { unique: ix.unique, multiEntry: ix.multiEntry });
              });
            });
          });
          open[schema.name] = db;
          return null;
        }
        case 'records': {
          var target = open[message.database];
          if (!target) throw new Error('records before database: ' + message.database);
          var tx = target.transaction(message.store, 'readwrite');
          var store = tx.objectStore(message.store);
          var inlineKeys = store.keyPath !== null && store.keyPath !== undefined;
          for (var i = 0; i < message.values.length; i++) {
            if (inlineKeys) store.put(message.values[i]);
            else store.put(message.values[i], message.keys[i]);
          }
          await transactionDone(tx);
          return null;
        }
        case 'localStorage': {
          if (storage) {
            storage.clear();
            message.entries.forEach(function (entry) { storage.setItem(entry[0], entry[1]); });
          }
          return null;
        }
        case 'finish': {
          var counts = {};
          for (var name in open) {
            if (!Object.prototype.hasOwnProperty.call(open, name)) continue;
            var db2 = open[name];
            counts[name] = {};
            var storeNames = listOf(db2.objectStoreNames);
            if (storeNames.length) {
              var tx2 = db2.transaction(storeNames, 'readonly');
              var pending = storeNames.map(function (storeName) {
                return request(tx2.objectStore(storeName).count()).then(function (c) { counts[name][storeName] = c; });
              });
              await Promise.all(pending);
            }
            db2.close();
          }
          open = {};
          return { counts: counts, localStorage: storage ? storage.length : 0 };
        }
        default:
          throw new Error('unknown message: ' + String(message && message.type));
      }
    }
    return { handle: handle };
  }

  /**
   * The parent page's run: puts the child page in an iframe, exports to it
   * over postMessage and reports to the native side. Every window-ish thing
   * is handed in so a test can stand it in.
   *
   *   idb, storage      — this (old) origin's indexedDB and localStorage
   *   origin            — this document's origin, which must be `expectedOrigin`
   *                       (the proof that the page got the old origin at all)
   *   childUrl          — the child page, on the new origin
   *   childOrigin       — the new origin, the only one listened to
   *   document, window  — to make the iframe and hear its messages
   *   report(message)   — to the native side: progress, then done or error
   */
  async function runParent(options) {
    var report = options.report;
    var pending = {};
    var nextId = 1;
    var onMessage = null;
    try {
      if (options.origin !== options.expectedOrigin) {
        throw new Error('origin mismatch: this page is ' + options.origin + ', expected ' + options.expectedOrigin);
      }
      var iframe = options.document.createElement('iframe');
      var readyResolve;
      var ready = new Promise(function (resolve) { readyResolve = resolve; });
      onMessage = function (event) {
        if (event.origin !== options.childOrigin) return;
        if (iframe.contentWindow && event.source !== iframe.contentWindow) return;
        var m = event.data;
        if (!m || typeof m !== 'object') return;
        if (m.type === 'ready') { readyResolve(); return; }
        var waiter = pending[m.id];
        if (!waiter) return;
        delete pending[m.id];
        if (m.type === 'ack') waiter.resolve(m.result);
        else if (m.type === 'fail') waiter.reject(new Error(m.message));
      };
      options.window.addEventListener('message', onMessage);
      iframe.setAttribute('src', options.childUrl);
      iframe.style.display = 'none';
      options.document.body.appendChild(iframe);
      await ready;
      var sentRecords = 0;
      var send = function (message) {
        return new Promise(function (resolve, reject) {
          var id = nextId++;
          pending[id] = { resolve: resolve, reject: reject };
          var payload = Object.assign({ id: id }, message);
          iframe.contentWindow.postMessage(payload, options.childOrigin);
        }).then(function (result) {
          if (message.type === 'records') {
            sentRecords += message.keys.length;
            report({ type: 'progress', records: sentRecords });
          }
          return result;
        });
      };
      var result = await exportOrigin(options.idb, options.storage, send, options);
      report({ type: 'done', databases: result.databases, records: result.records, localStorage: result.localStorage });
    } catch (e) {
      report({ type: 'error', message: String((e && e.message) || e) });
    } finally {
      if (onMessage) options.window.removeEventListener('message', onMessage);
    }
  }

  /**
   * The child page's run: imports what the parent sends, one message at a
   * time, answering each with `ack` (and the reply) or `fail`. Only the
   * parent's origin is heard, and only it is answered.
   */
  function runChild(options) {
    var importer = createImporter(options.idb, options.storage);
    var queue = Promise.resolve();
    options.window.addEventListener('message', function (event) {
      if (event.origin !== options.parentOrigin) return;
      var m = event.data;
      if (!m || typeof m !== 'object' || m.id === undefined) return;
      var source = event.source;
      queue = queue.then(function () {
        return importer.handle(m);
      }).then(function (result) {
        source.postMessage({ type: 'ack', id: m.id, result: result }, options.parentOrigin);
      }, function (e) {
        source.postMessage({ type: 'fail', id: m.id, message: String((e && e.message) || e) }, options.parentOrigin);
      });
    });
    options.parent.postMessage({ type: 'ready' }, options.parentOrigin);
  }

  /** {@link runParent} over the real page; what the Swift bootstrap calls. */
  function runParentInPage(config) {
    return runParent({
      idb: typeof indexedDB !== 'undefined' ? indexedDB : null,
      storage: typeof localStorage !== 'undefined' ? localStorage : null,
      origin: self.location.origin,
      expectedOrigin: config.expectedOrigin,
      childUrl: config.childUrl,
      childOrigin: config.childOrigin,
      document: self.document,
      window: self,
      report: config.report,
    });
  }

  /** {@link runChild} over the real page; what the served child page calls. */
  function runChildInPage(config) {
    runChild({
      idb: typeof indexedDB !== 'undefined' ? indexedDB : null,
      storage: typeof localStorage !== 'undefined' ? localStorage : null,
      parentOrigin: config.parentOrigin,
      window: self,
      parent: self.parent,
    });
  }

  return {
    exportOrigin: exportOrigin,
    createImporter: createImporter,
    readSchema: readSchema,
    runParent: runParent,
    runChild: runChild,
    runParentInPage: runParentInPage,
    runChildInPage: runChildInPage,
    PAGE_BYTES: PAGE_BYTES,
  };
});
